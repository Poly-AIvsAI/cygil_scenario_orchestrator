"""Génération et exécution confirmée de Vagrant pour les seules cibles.

Les VM CyGIL, CALDERA, ONOS et Mininet ne traversent jamais cet adaptateur. Le
mode dry-run retourne les commandes exactes sans contacter Vagrant.
"""

from __future__ import annotations

import hashlib
import json
import os
import subprocess
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

from ..models import InterfacePurpose, OSFamily, Scenario


class VagrantSafetyError(RuntimeError):
    """Refus d'une commande ambiguë, non confirmée ou dirigée vers l'infrastructure."""


@dataclass(frozen=True)
class VagrantCommand:
    """Commande prévisualisable avec sa cible et son niveau de confirmation."""

    action: str
    target_id: str | None
    arguments: tuple[str, ...]
    mutating: bool = True
    dedicated_confirmation: bool = False

    def display(self) -> str:
        """Produit une représentation lisible sans passer par un interpréteur shell."""

        return subprocess.list2cmdline(self.arguments)


@dataclass(frozen=True)
class VagrantExecutionResult:
    """Sortie bornée d'une commande afin d'alimenter le suivi par cible."""

    command: VagrantCommand
    returncode: int | None
    stdout: str
    stderr: str
    mode: str


def _ruby(value: str) -> str:
    """Protège une valeur utilisateur avant son insertion dans le DSL Ruby."""

    return value.replace("\\", "/").replace('"', '\\"')


def _vmware_mac(value: str) -> str:
    """Normalise une MAC au format attendu dans un fichier VMX."""

    return value.replace("-", ":").lower()


def render_vagrantfile(scenario: Scenario, destination: str | Path) -> Path:
    """Génère uniquement les cibles et conserve chaque correspondance réseau.

    Les cibles ne reçoivent jamais VMnet0. Leur première carte utilise le VMnet
    DHCP d'amorçage, puis leurs interfaces de scénario rejoignent les VMnet
    dédiés calculés par raccordement.
    """

    lines = [
        'Vagrant.configure("2") do |config|',
        '  # Generated by CyGIL: execution still requires the displayed confirmation.',
        '  config.vm.synced_folder ".", "/vagrant", disabled: true',
    ]
    for target in scenario.targets:
        lines.extend(
            [
                f'  config.vm.define "{_ruby(target.id)}" do |vm|',
                f'    vm.vm.box = "{_ruby(target.template)}"',
                f'    vm.vm.hostname = "{_ruby(target.hostname)}"',
            ]
        )
        temporary_access = target.temporary_management
        lines.extend(
            [
                '    vm.vm.provider "vmware_desktop" do |provider|',
                f'      provider.vmx["memsize"] = "{target.memory_mb}"',
                f'      provider.vmx["numvcpus"] = "{target.cpus}"',
            ]
        )
        if scenario.vagrant.clone_directory:
            lines.append(f'      provider.clone_directory = "{_ruby(scenario.vagrant.clone_directory)}"')
        bootstrap_index = 0
        if temporary_access.enabled and scenario.vagrant.bootstrap_network:
            # Cette carte fournit uniquement l'accès DHCP initial. Elle n'est
            # jamais compilée dans CyGIL et sera désactivée dans l'OS invité.
            lines.extend(
                [
                    f'      provider.vmx["ethernet{bootstrap_index}.present"] = "TRUE"',
                    f'      provider.vmx["ethernet{bootstrap_index}.connectionType"] = "custom"',
                    f'      provider.vmx["ethernet{bootstrap_index}.vnet"] = "{_ruby(scenario.vagrant.bootstrap_network)}"',
                    f'      provider.vmx["ethernet{bootstrap_index}.startConnected"] = "TRUE"',
                    f'      # ethernet{bootstrap_index}: temporary DHCP bootstrap; disable in guest before snapshot',
                ]
            )

        # Les cartes Mininet utilisent des indices explicites lorsqu'ils sont
        # connus. Sans VMnet calculé et confirmé, la carte n'est pas branchée silencieusement.
        next_index = 1 if temporary_access.enabled and scenario.vagrant.bootstrap_network else 0
        scenario_interfaces = [
            interface for interface in target.interfaces if interface.purpose == InterfacePurpose.SCENARIO
        ]
        for interface in scenario_interfaces:
            adapter_index = interface.vmware_adapter_index if interface.vmware_adapter_index is not None else next_index
            next_index = max(next_index, adapter_index + 1)
            if not interface.vmware_network:
                lines.append(
                    f'      # {interface.name}: VMware network not confirmed for {interface.network}/{interface.connected_switch}'
                )
                continue
            lines.extend(
                [
                    f'      provider.vmx["ethernet{adapter_index}.present"] = "TRUE"',
                    f'      provider.vmx["ethernet{adapter_index}.connectionType"] = "custom"',
                    f'      provider.vmx["ethernet{adapter_index}.vnet"] = "{_ruby(interface.vmware_network)}"',
                    f'      provider.vmx["ethernet{adapter_index}.startConnected"] = "TRUE"',
                ]
            )
            # Une MAC appartient toujours à cette interface précise. L'ancien
            # champ target.mac est retiré lors du chargement des sauvegardes.
            mac = interface.mac
            if mac:
                lines.extend(
                    [
                        f'      provider.vmx["ethernet{adapter_index}.addressType"] = "static"',
                        f'      provider.vmx["ethernet{adapter_index}.address"] = "{_vmware_mac(mac)}"',
                    ]
                )
        lines.append("    end")
        if target.guest_access:
            lines.append(f'    vm.vm.communicator = "{target.guest_access.communicator.value}"')
            if target.guest_access.communicator.value == "ssh" and target.guest_access.username:
                lines.append(f'    vm.ssh.username = "{_ruby(target.guest_access.username)}"')
            if target.guest_access.communicator.value == "winrm" and target.guest_access.username:
                lines.append(f'    vm.winrm.username = "{_ruby(target.guest_access.username)}"')
        elif target.os_family == OSFamily.WINDOWS:
            # Le brouillon historique reste chargeable, mais la validation bloque
            # un déploiement réel tant que WinRM ou SSH n'est pas confirmé.
            lines.append('    vm.vm.communicator = "winrm"')
        lines.append("  end")
    lines.append("end")
    path = Path(destination)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def build_vagrant_commands(
    scenario: Scenario,
    executable: str = "vagrant",
    *,
    installed_boxes: set[str] | None = None,
) -> list[VagrantCommand]:
    """Construit les commandes exactes d'import et de création, dans l'ordre sûr."""

    commands: list[VagrantCommand] = []
    seen_templates: set[str] = set()
    for target in scenario.targets:
        if target.template in seen_templates:
            continue
        seen_templates.add(target.template)
        box_path = scenario.vagrant.box_paths.get(target.template)
        if box_path and target.template not in (installed_boxes or set()):
            commands.append(
                VagrantCommand(
                    action="box_add",
                    target_id=None,
                    arguments=(
                        executable,
                        "box",
                        "add",
                        str(Path(box_path).resolve()),
                        "--name",
                        target.template,
                        "--provider",
                        "vmware_desktop",
                    ),
                )
            )
    for target in scenario.targets:
        commands.append(
            VagrantCommand(
                action="status",
                target_id=target.id,
                arguments=(executable, "status", target.id, "--machine-readable"),
                mutating=False,
            )
        )
        commands.append(
            VagrantCommand(
                action="up",
                target_id=target.id,
                arguments=(
                    executable,
                    "up",
                    target.id,
                    "--provider",
                    "vmware_desktop",
                    "--no-destroy-on-error",
                    "--no-parallel",
                ),
            )
        )
    return commands


def command_confirmation_token(commands: list[VagrantCommand]) -> str:
    """Lie la confirmation à la liste exacte affichée et empêche un plan périmé."""

    payload = json.dumps([command.arguments for command in commands], ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:12].upper()


class VagrantTargetAdapter:
    """Exécute un plan confirmé en refusant toute cible hors du scénario."""

    def __init__(self, scenario: Scenario, working_directory: str | Path, *, dry_run: bool = True) -> None:
        self.scenario = scenario
        self.working_directory = Path(working_directory)
        self.dry_run = dry_run
        self.target_ids = {target.id for target in scenario.targets}
        self.infrastructure_ids = {machine.id for machine in scenario.infrastructure}

    def execute(
        self,
        commands: list[VagrantCommand],
        *,
        confirmation_token: str | None = None,
        allow_destroy: bool = False,
        progress_callback: Callable[[VagrantExecutionResult], None] | None = None,
    ) -> list[VagrantExecutionResult]:
        """Lance séquentiellement les commandes après validation de leur empreinte."""

        expected = command_confirmation_token(commands)
        if not self.dry_run and confirmation_token != expected:
            raise VagrantSafetyError("Le plan Vagrant exact n'a pas été confirmé")
        self._validate_commands(commands, allow_destroy=allow_destroy)
        if self.dry_run:
            results = [VagrantExecutionResult(item, None, item.display(), "", "dry-run") for item in commands]
            if progress_callback:
                for result in results:
                    progress_callback(result)
            return results

        self.working_directory.mkdir(parents=True, exist_ok=True)
        environment = os.environ.copy()
        if self.scenario.vagrant.clone_directory:
            environment["VAGRANT_VMWARE_CLONE_DIRECTORY"] = str(
                Path(self.scenario.vagrant.clone_directory).resolve()
            )
        results: list[VagrantExecutionResult] = []
        box_import_failed = False
        for command in commands:
            if command.action == "up" and box_import_failed:
                skipped = VagrantExecutionResult(
                        command,
                        -1,
                        "",
                        "Création ignorée car au moins une box locale n'a pas pu être importée.",
                        "real",
                    )
                results.append(skipped)
                if progress_callback:
                    progress_callback(skipped)
                continue
            result = subprocess.run(
                list(command.arguments),
                cwd=self.working_directory,
                env=environment,
                capture_output=True,
                text=True,
                encoding="utf-8",
                timeout=None,
                check=False,
            )
            completed = VagrantExecutionResult(command, result.returncode, result.stdout, result.stderr, "real")
            results.append(completed)
            if progress_callback:
                progress_callback(completed)
            if command.action == "box_add" and result.returncode != 0:
                box_import_failed = True
            # Une cible en échec n'autorise ni destruction ni arrêt global : les
            # autres résultats restent observables et reprenables indépendamment.
        return results

    def _validate_commands(self, commands: list[VagrantCommand], *, allow_destroy: bool) -> None:
        """Applique la liste blanche et la confirmation dédiée de destruction."""

        allowed_actions = {"box_add", "up", "status", "halt", "snapshot", "destroy"}
        for command in commands:
            if command.action not in allowed_actions:
                raise VagrantSafetyError(f"Action Vagrant non autorisée : {command.action}")
            if command.target_id:
                if command.target_id in self.infrastructure_ids or command.target_id not in self.target_ids:
                    raise VagrantSafetyError(f"Vagrant ne peut pas prendre en charge {command.target_id}")
            if command.action == "destroy" and not (allow_destroy and command.dedicated_confirmation):
                raise VagrantSafetyError("vagrant destroy exige une confirmation dédiée")
